package com.vk.starscriptmusic.data.local.backup

/**
 * Lightweight JSON-serializable backup payload for Google Drive appDataFolder and local export.
 */
data class StarscriptBackupData(
    val version: Int = 1,
    val exportTimestamp: Long = System.currentTimeMillis(),
    val playlists: List<BackupPlaylist> = emptyList(),
    val favoriteTrackIds: List<Long> = emptyList(),
    val playCounts: List<BackupPlayCount> = emptyList()
)

data class BackupPlaylist(
    val name: String,
    val description: String? = null,
    val trackIds: List<Long> = emptyList(),
    val isAutoGenerated: Boolean = false,
    val artistFilter: String? = null
)

data class BackupPlayCount(
    val trackId: Long,
    val playCount: Int,
    val lastPlayedTimestamp: Long,
    val completionPercentage: Float
)
