package com.vk.starscriptmusic.data.local.db.entity

import androidx.room.Embedded
import androidx.room.Junction
import androidx.room.Relation
import com.vk.starscriptmusic.domain.model.Playlist

/**
 * Relation helper uniting PlaylistEntity with its constituent TrackEntity items.
 */
data class PlaylistWithTracks(
    @Embedded
    val playlist: PlaylistEntity,

    @Relation(
        parentColumn = "id",
        entityColumn = "id",
        associateBy = Junction(
            value = PlaylistTrackCrossRef::class,
            parentColumn = "playlistId",
            entityColumn = "trackId"
        )
    )
    val tracks: List<TrackEntity>
) {
    fun toDomain(): Playlist {
        return Playlist(
            id = playlist.id,
            name = playlist.name,
            description = playlist.description,
            createdAt = playlist.createdAt,
            isAutoGenerated = playlist.isAutoGenerated,
            artistFilter = playlist.artistFilter,
            tracks = tracks.map { it.toDomain() }
        )
    }
}
